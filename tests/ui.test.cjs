const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
let browser;
(async()=>{
 browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{}),args:['--disable-gpu']});
 const page=await browser.newPage({viewport:{width:412,height:915},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('dialog',d=>d.accept());
 await page.goto(pathToFileURL(path.resolve(__dirname,'../app/src/main/assets/index.html')).href);
 await page.waitForSelector('.calendar-grid .day:not(.empty)');
 await page.evaluate(()=>{localStorage.clear();});await page.reload();
 assert.equal(await page.locator('.legend').innerText(),'出差\n办公\n休假');
 assert.equal(await page.locator('.day.business').count(),3);
 assert.equal(await page.locator('.day.office').count(),2);
 assert.equal(await page.locator('.day.holiday').count(),2);
 assert.equal(await page.locator('article.receipt').count(),2);
 const report=path.resolve(__dirname,'../verification');fs.mkdirSync(report,{recursive:true});
 await page.screenshot({path:path.join(report,'calendar-preview.png'),fullPage:false});
 await page.locator('[data-tab="export"]').click();
 assert.equal(await page.locator('[data-exportcat]').count(),5);
 assert.equal(await page.locator('#exportFrom').count(),0,'No date filtering before category choice');
 await page.screenshot({path:path.join(report,'export-categories-preview.png'),fullPage:true});
 await page.locator('[data-exportcat="0"]').click();
 assert.equal(await page.locator('[data-toggle]').count(),1);
 assert.ok((await page.locator('.summary-strip').innerText()).includes('£6.90'));
 await page.locator('#toggleAll').click();assert.equal(await page.locator('#generateExport').isDisabled(),true);
 await page.locator('[data-toggle]').click();assert.equal(await page.locator('#generateExport').isDisabled(),false);
 await page.screenshot({path:path.join(report,'export-dates-preview.png'),fullPage:true});
 await page.locator('[data-tab="calendar"]').click();await page.locator('#markDay').click();
 const key=await page.locator('#markFrom').inputValue();await page.locator('#markType').selectOption('office');await page.locator('#saveMark').click();
 assert.ok((await page.locator(`[data-day="${key}"]`).getAttribute('class')).includes('office'));
 await page.locator('#addReceipt').click();assert.equal(await page.locator('#importNew').isDisabled(),true);
 await page.locator('[data-choose="2"]').click();await page.locator('#importNew').click();
 await page.waitForSelector('#editDate');assert.equal(await page.locator('#editAmount').inputValue(),'12.80');
 assert.equal(await page.locator('#editCategory').inputValue(),'出差餐补');
 assert.equal(await page.locator('select option[value="GBP"]').count(),0);
 await page.locator('#editMerchant').fill('<img src=x onerror=alert(1)>');await page.locator('#editLocation').fill('London');
 await page.locator('#editConfirmed').check();await page.locator('#saveReceipt').click();
 await page.locator('[data-tab="receipts"]').click();
 assert.ok((await page.locator('main').innerText()).includes('<img src=x onerror=alert(1)>'));
 assert.equal(await page.locator('main img[src="x"]').count(),0,'Merchant text must be escaped');
 const total=await page.locator('article.receipt').count();assert.equal(total,6);
 await page.reload();await page.locator('[data-tab="receipts"]').click();assert.equal(await page.locator('article.receipt').count(),6,'Preview storage persists on reload');
 await page.setViewportSize({width:360,height:800});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'No horizontal overflow at 360px');
 assert.deepEqual(errors,[]);
 await browser.close();fs.writeFileSync(path.join(report,'ui-test-result.json'),JSON.stringify({status:'passed',checks:['calendar colours and labels','day invoice list','five export categories before dates','selection and totals','day marking','local image import flow (simulated)','GBP-only interface','HTML escaping','preview persistence','360px layout'],limitations:'Android bridge, camera, ML Kit, SQLite and native export are not executed by this browser test.'},null,2));
 console.log('UI smoke tests passed. Screenshots saved to verification/.');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();});
